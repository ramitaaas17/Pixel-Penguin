const { chromium } = require('../.tools/web-test/node_modules/playwright');
const fs = require('fs');
(async () => {
  fs.mkdirSync('docs/web', { recursive: true });
  const browser = await chromium.launch({headless: true, args: ['--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport: {width: 960, height: 600}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('401 (Unauthorized)')) errors.push(message.text()); });
  await page.goto('http://localhost:3000/');
  await page.waitForFunction(() => !document.getElementById('status'), {timeout: 60000});
  await page.waitForTimeout(1500);
  await page.screenshot({path: 'docs/web/welcome.png'});
  console.log('PASS WebAssembly inicia la plaza en Chromium');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(700);
  await page.keyboard.type('web_invalid_user');
  await page.keyboard.press('Tab');
  await page.keyboard.type('invalid-password');
  const loginResponse = page.waitForResponse(r => r.url().endsWith('/auth/login'));
  await page.keyboard.press('Enter');
  const response = await loginResponse;
  if (response.status() !== 401) throw new Error('Login inválido no devuelve 401');
  if (new URL(response.url()).port !== '3000') throw new Error('La API no utiliza el mismo origen');
  await page.waitForTimeout(700);
  await page.screenshot({path: 'docs/web/invalid-login.png'});
  console.log('PASS formulario real llama al backend en el mismo origen y recibe 401');
  await page.reload();
  await page.waitForFunction(() => !document.getElementById('status'));
  await page.waitForTimeout(700);
  await page.keyboard.press('Tab');
  await page.keyboard.press('Tab');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(700);
  await page.screenshot({path: 'docs/web/guest.png'});
  await page.mouse.click(580, 400);
  await page.waitForTimeout(700);
  await page.screenshot({path: 'docs/web/guest-after-click.png'});
  console.log('PASS entrada invitada y clic de movimiento ejecutados');
  const username = 'web_' + require('crypto').randomBytes(8).toString('hex');
  const password = require('crypto').randomBytes(16).toString('hex');
  let created = false;
  try {
    await page.reload();
    await page.waitForFunction(() => !document.getElementById('status'));
    await page.waitForTimeout(700);
    await page.keyboard.press('Tab');
    await page.keyboard.press('Enter');
    await page.waitForTimeout(400);
    await page.keyboard.type(username);
    await page.keyboard.press('Enter');
    await page.keyboard.type(password);
    await page.keyboard.press('Enter');
    await page.keyboard.type(password);
    const registration = page.waitForResponse(r => r.url().endsWith('/auth/register'));
    await page.keyboard.press('Enter');
    const registered = await registration;
    if (registered.status() !== 201) throw new Error('Registro Web falló');
    created = true;
    const data = await registered.json();
    if (data.jugador.monedas !== 100) throw new Error('Saldo inicial incorrecto');
    await page.waitForTimeout(700);
    await page.screenshot({path: 'docs/web/authenticated.png'});
    console.log('PASS registro desde Web crea identidad y saldo confirmado de 100 monedas');
    await page.reload();
    await page.waitForFunction(() => !document.getElementById('status'));
    await page.waitForTimeout(700);
    await page.keyboard.press('Enter');
    await page.waitForTimeout(400);
    await page.keyboard.type(username);
    await page.keyboard.press('Enter');
    await page.keyboard.type(password);
    const login = page.waitForResponse(r => r.url().endsWith('/auth/login'));
    await page.keyboard.press('Enter');
    if ((await login).status() !== 200) throw new Error('Login Web falló');
    console.log('PASS login desde Web después de recargar');
  } finally {
    await browser.close();
    if (created) {
      const sql = `BEGIN; DELETE FROM accounts WHERE username = '${username}'; DELETE FROM jugadores WHERE nombre = '${username}'; COMMIT;`;
      require('child_process').execFileSync('docker', ['compose', 'exec', '-T', 'db-jugadores', 'psql', '-U', 'jugadoresapp', '-d', 'jugadoresdb', '-v', 'ON_ERROR_STOP=1', '-c', sql], {stdio:'pipe'});
      console.log('PASS cuenta temporal eliminada');
    }
  }
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('WEB_VALIDATION failures=0');
})().catch(error => {console.error(error); process.exit(1);});
